package com.cqu.coit13230.AIBasedCustomerSupport.model;

/**
 * Defines the possible account statuses for users within the
 * AI-Based Customer Support system.
 *
 * <p>The status indicates whether a user account is currently
 * enabled or inactive within the system.</p>
 */
public enum UserStatus {

    /**
     * Indicates that the user account is active and available for use.
     */
    ACTIVE,

    /**
     * Indicates that the user account is inactive and unavailable for use.
     */
    INACTIVE
}